function generateUFork(order) {
  // order 1: n=2, order 2: n=4, order 3: n=8, etc.
  const n = Math.pow(2, order);
  
  if (order === 1) {
    return [{col:1,row:1},{col:0,row:1},{col:0,row:0},{col:1,row:0}];
  }
  
  if (order === 2) {
    // Step 2: generate as a shifted version of the zigzag pattern
    // The zigzag produces the same cycle but starting at (1,3).
    // Target starts at (1,1).
    // Shift the generated path to start at the correct position.
    const raw = generateZigzag(4);
    // Find the index in raw that corresponds to step2[0]=(1,1)
    const startIdx = raw.findIndex(p => p.col === 1 && p.row === 1);
    // Circular shift
    return [...raw.slice(startIdx), ...raw.slice(0, startIdx)];
  }
  
  if (order === 3) {
    return generateZigzag(8);
  }
  
  // For order >= 4: recursive construction
  // 1. Generate the previous level's path (for the center n/2 x n/2)
  const innerPath = generateUFork(order - 1);
  const innerN = n / 2;
  
  // 2. Compute the shift for the center embedding
  const shift = computeShift(order);
  
  // 3. Shift the inner path and offset to center
  const offset = n / 4;
  const shiftedInner = [];
  for (let i = 0; i < innerPath.length; i++) {
    const j = (i + shift) % innerPath.length;
    shiftedInner.push({
      col: innerPath[j].col + offset,
      row: innerPath[j].row + offset
    });
  }
  
  // 4. Find the split point: where does the inner path cross the center boundary?
  // The center region is [offset, offset+innerN-1] in both col and row.
  // The split happens where two consecutive cells are on the boundary
  // and the path would exit to the frame.
  // From the analysis: the frame entry is at (quarter-1, half) = (offset-1, offset+innerN/2)
  // Actually, the entry point from center to frame:
  // step4: center exits at (4,8) -> frame at (3,8). (4,8) is center coord (0,4).
  // In the inner path (shifted), this should be the point where the path
  // is at col=offset and transitions to col=offset-1.
  
  // The split in step4: after 20 center cells. The 20th cell is at (0,4) in inner coords,
  // which is (4,8) in global coords. The 21st cell is at (0,3) = (4,7) in global.
  // The frame connects (3,8) [one left of (4,8)] to (3,7) [one left of (4,7)].
  
  // So the split is where two consecutive inner cells are:
  // cell A at (offset, half) and cell B at (offset, half-1)
  // i.e., inner coords (0, innerN/2) and (0, innerN/2-1)
  // These are adjacent along col 0, crossing the midpoint.
  
  // In step 3, the positions at d=6 and d=7 are (0,4) and (0,3).
  // Shifted by 51: positions 51+19=70 mod 64 = 6, and 51+20=71 mod 64 = 7.
  // So split after rank 19 (0-indexed), i.e., after the first 20 elements.
  
  // The split point K: find the index in shiftedInner where
  // shiftedInner[K].col == offset && shiftedInner[K].row == offset + innerN/2
  // AND shiftedInner[K+1].col == offset && shiftedInner[K+1].row == offset + innerN/2 - 1
  
  let splitK = -1;
  for (let i = 0; i < shiftedInner.length - 1; i++) {
    if (shiftedInner[i].col === offset && shiftedInner[i].row === offset + innerN / 2 &&
        shiftedInner[i + 1].col === offset && shiftedInner[i + 1].row === offset + innerN / 2 - 1) {
      splitK = i;
      break;
    }
  }
  
  if (splitK === -1) {
    console.log('ERROR: could not find split point!');
    console.log('Looking for:', offset, offset + innerN/2, '->', offset, offset + innerN/2 - 1);
    // Print first few shifted inner cells
    for (let i = 0; i < 25; i++) {
      console.log(`  i=${i}: (${shiftedInner[i].col},${shiftedInner[i].row})`);
    }
    return shiftedInner; // fallback
  }
  
  console.log(`Split at K=${splitK}`);
  
  // 5. Split inner into entering and exiting parts
  const enterPart = shiftedInner.slice(0, splitK + 1);
  const exitPart = shiftedInner.slice(splitK + 1);
  
  // 6. Generate the frame path
  const framePath = generateFrame(n);
  
  // 7. Combine: entering center + frame + exiting center
  return [...enterPart, ...framePath, ...exitPart];
}

function generateZigzag(n) {
  const path = [];
  let cx, cy;
  function put(col, row) { path.push({col, row}); cx = col; cy = row; }
  function moveBy(dx, dy, steps) {
    for (let i = 0; i < steps; i++) { cx += dx; cy += dy; put(cx, cy); }
  }
  
  const half = n / 2;
  put(half - 1, n - 1);
  moveBy(-1, 0, half - 1);
  moveBy(0, -1, n - 1);
  moveBy(1, 0, n - 1);
  moveBy(0, 1, half - 1);
  
  let goingLeft = true;
  for (let scan = 0; scan < half - 1; scan++) {
    const isLast = (scan === half - 2);
    if (goingLeft) moveBy(-1, 0, cx - (isLast ? 1 : 2));
    else moveBy(1, 0, (isLast ? (n - 1) : (n - 2)) - cx);
    if (!isLast) moveBy(0, -1, 1);
    goingLeft = !goingLeft;
  }
  
  moveBy(0, 1, (n - 2) - cy);
  
  let goingRight = true;
  for (let scan = 0; scan < half - 1; scan++) {
    const isLast = (scan === half - 2);
    if (goingRight) moveBy(1, 0, (isLast ? (n - 1) : (n - 2)) - cx);
    else moveBy(-1, 0, cx - (isLast ? 1 : 2));
    if (!isLast) moveBy(0, -1, 1);
    goingRight = !goingRight;
  }
  
  moveBy(0, 1, (n - 1) - cy);
  moveBy(-1, 0, half - 1);
  
  return path;
}

function computeShift(order) {
  // shift(k) = 4^k - shift(k-1), shift(1) = 3
  // But the shift is for the INNER path, which is order-1.
  // For order 4: center is order 3 (64 cells), shift is 51.
  // shift(3) = 64 - 13 = 51
  // shift(2) = 16 - 3 = 13
  // shift(1) = 3
  // 
  // The recurrence: s(1)=3, s(k)=4^k-s(k-1)
  // For order k, the shift for the inner path is s(k-1).
  // Wait no: for order 4, inner is order 3 with 64 cells, shift=51.
  // s(3) = 51. Let me verify: s(1)=3, s(2)=16-3=13, s(3)=64-13=51. Yes.
  // For order k, shift = s(k-1).
  
  let s = 3;
  for (let k = 2; k < order; k++) {
    s = Math.pow(4, k) - s;
  }
  return s;
}

function generateFrame(n) {
  // Generate the frame path for an n x n grid.
  // The frame fills all cells NOT in the center (n/2) x (n/2) region.
  // Entry: from center at (quarter, half) to frame at (quarter-1, half)
  // Exit: from frame at (quarter-1, half-1) to center at (quarter, half-1)
  
  const half = n / 2;
  const quarter = n / 4;
  
  const path = [];
  let cx, cy;
  function put(col, row) { path.push({col, row}); cx = col; cy = row; }
  function moveBy(dx, dy, steps) {
    for (let i = 0; i < steps; i++) { cx += dx; cy += dy; put(cx, cy); }
  }
  
  // Start at (quarter-1, half) = inner boundary, left side
  put(quarter - 1, half);
  
  // Outward spiral
  for (let level = 0; level < quarter - 1; level++) {
    const vertSteps = quarter + level;
    const horizSteps = half + 1 + 2 * level;
    
    // UP
    moveBy(0, 1, vertSteps);
    
    if (level % 2 === 0) {
      // RIGHT
      moveBy(1, 0, horizSteps);
      // DOWN
      moveBy(0, -1, vertSteps);
      // Step RIGHT
      moveBy(1, 0, 1);
    } else {
      // LEFT
      moveBy(-1, 0, horizSteps);
      // DOWN
      moveBy(0, -1, vertSteps);
      // Step LEFT
      moveBy(-1, 0, 1);
    }
  }
  
  // Final UP to corner
  moveBy(0, 1, half - 1);
  
  // Outer perimeter: L, D, R
  moveBy(-1, 0, n - 1);
  moveBy(0, -1, n - 1);
  moveBy(1, 0, n - 1);
  
  // UP from bottom-right
  moveBy(0, 1, half - 1);
  
  // Inward spiral (mirror of outward)
  for (let level = quarter - 2; level >= 0; level--) {
    const vertSteps = quarter + level;
    const horizSteps = half + 1 + 2 * level;
    
    if (level % 2 === 0) {
      // Step LEFT
      moveBy(-1, 0, 1);
      // DOWN
      moveBy(0, -1, vertSteps);
      // LEFT
      moveBy(-1, 0, horizSteps);
      // UP
      moveBy(0, 1, vertSteps);
    } else {
      // Step RIGHT
      moveBy(1, 0, 1);
      // DOWN
      moveBy(0, -1, vertSteps);
      // RIGHT
      moveBy(1, 0, horizSteps);
      // UP
      moveBy(0, 1, vertSteps);
    }
  }
  
  return path;
}

